// Copies the pure pricing/billing code from src/domain into supabase/functions/_shared/domain
// so Edge Functions (Deno) run exactly the same code as the app. Deno needs file extensions
// on relative imports, so `from './money'` becomes `from './money.ts'`.
//
//   node scripts/sync-domain.mjs          write the copies
//   node scripts/sync-domain.mjs --check  exit 1 if the copies are out of date (CI, Jest)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'src/domain');
const to = join(root, 'supabase/functions/_shared/domain');
const FILES = ['money.ts', 'zoned-time.ts', 'pricing.ts', 'sessions.ts', 'billing.ts'];
const HEADER =
  '// GENERATED by scripts/sync-domain.mjs from src/domain. Do not edit: change src/domain and\n' +
  '// run `npm run domain:sync`.\n';

function transform(source) {
  const code = source.replace(/(from\s+['"])(\.\.?\/[^'"]+?)(['"])/g, (match, start, path, end) =>
    path.endsWith('.ts') ? match : `${start}${path}.ts${end}`,
  );
  return HEADER + code.replace(/\r\n/g, '\n');
}

for (const file of FILES) {
  for (const m of readFileSync(join(from, file), 'utf8').matchAll(/from\s+['"]([^'"]+)['"]/g)) {
    const spec = m[1];
    if (!spec.startsWith('./') || !FILES.includes(`${spec.slice(2)}.ts`)) {
      console.error(`${file} imports "${spec}": only the copied domain files may be imported.`);
      process.exit(1);
    }
  }
}

const expected = new Map(FILES.map((f) => [f, transform(readFileSync(join(from, f), 'utf8'))]));

if (process.argv.includes('--check')) {
  let current = [];
  try {
    current = readdirSync(to);
  } catch {
    // missing folder: everything is out of date
  }
  const stale = FILES.filter((f) => {
    try {
      return readFileSync(join(to, f), 'utf8') !== expected.get(f);
    } catch {
      return true;
    }
  });
  const extra = current.filter((f) => !FILES.includes(f));
  if (stale.length || extra.length) {
    console.error(
      `supabase/functions/_shared/domain is out of date (${[...stale, ...extra].join(', ')}). ` +
        'Run `npm run domain:sync`.',
    );
    process.exit(1);
  }
  console.log('supabase/functions/_shared/domain is up to date.');
} else {
  rmSync(to, { recursive: true, force: true });
  mkdirSync(to, { recursive: true });
  for (const [file, code] of expected) writeFileSync(join(to, file), code);
  console.log(`Copied ${FILES.length} files to supabase/functions/_shared/domain.`);
}
